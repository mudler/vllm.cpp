template <size_t N>
std::vector<uint8_t> BVec(const int32_t (&a)[N]) {
  std::vector<uint8_t> v(N);
  for (size_t i = 0; i < N; ++i) v[i] = a[i] != 0 ? 1U : 0U;
  return v;
}

