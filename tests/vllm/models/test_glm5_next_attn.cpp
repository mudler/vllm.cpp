// The largest absolute difference, and the index it happened at.
struct Diff {
  double max_abs = 0.0;
  size_t at = 0;
  size_t n_differing = 0;
  bool any_nonfinite = false;
};

Diff Compare(const std::vector<float>& got, const float* want, size_t n,
             double tol) {
  Diff d;
  REQUIRE(got.size() == n);
  for (size_t i = 0; i < n; ++i) {
    if (!std::isfinite(got[i])) d.any_nonfinite = true;
    const double e = std::fabs(static_cast<double>(got[i]) - want[i]);
    if (e > tol) ++d.n_differing;
    if (e > d.max_abs) {
      d.max_abs = e;
      d.at = i;
    }
  }
  return d;
}

