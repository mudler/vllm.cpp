// GLM-5.3-Flash W3 gate — the DSA indexer's k-pool compression and its ragged
// tail, against the RUN output of `transformers` v5.16.1.
//
// Row MODEL-MM-glm5-next-glm5-next-for-conditional-generation, issue #2213,
// `.agents/specs/glm5-next-flash.md` section W3.
//
// ─── WHAT MAKES THIS FIXTURE ABLE TO FAIL ───────────────────────────────────
//
// Three properties, each chosen because dropping it makes the whole file a
// tautology that a wrong port passes:
//
//  1. `seq_len` 21 is STRICTLY GREATER than `index_topk` 8. At or below
//     `index_topk` a top-k over raw tokens selects EVERYTHING, the selection is
//     the identity, and the pooling is unobservable. `.agents/specs/
//     glm5-next-flash.md` makes running past that threshold a requirement, not
//     a note, and the campaign's sibling row already paid for the same trap.
//  2. Row 1 is LEFT-PADDED by three tokens, so its pool grid starts at token 3.
//     A port that pools from slot 0 passes row 0 and fails row 1.
//  3. Selection error is BIMODAL, not continuous: the top-k either picks the
//     right pool or a completely different one, and the OUTPUT values of a
//     wrong-but-adjacent pool can be arbitrarily close. So this file asserts
//     SET EQUALITY of the selected indices and PRINTS THE MARGIN; a tolerance
//     on the values alone passes a wrong selection whose values happen to agree.
//     The fixture is tie-free by construction and the smallest margin over its
//     17 discriminating rows is reported by the case below.
//
// ─── THE ORACLE ─────────────────────────────────────────────────────────────
// `glm5_next_dsa_goldens.inc` is GENERATED by
// `fixtures/gen_glm5_next_dsa_goldens.py`, which RUNS the unmodified
// `Glm5NextTextIndexer` at transformers v5.16.1 — the lane revision W0 (#2096)
// recorded — through its own `__call__` and its own public sub-methods. Nothing
// in it is transcribed from our C++.
