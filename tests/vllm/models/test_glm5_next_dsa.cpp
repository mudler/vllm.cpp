template <typename T, size_t N>
std::vector<T> Vec(const T (&a)[N]) {
  return std::vector<T>(a, a + N);
}

std::vector<uint8_t> Bytes(const int32_t* a, size_t n) {
  std::vector<uint8_t> v(n);
  for (size_t i = 0; i < n; ++i) v[i] = a[i] != 0 ? 1 : 0;
  return v;
}

IndexerDims FixtureDims() {
  IndexerDims d;
  d.hidden_size = g::kHidden;
  d.q_lora_rank = g::kQLora;
  d.n_heads = g::kNHeads;
  d.head_dim = g::kHeadDim;
  d.index_topk = g::kIndexTopk;
  d.index_kpool = g::kIndexKpool;
  d.always_select_tail = true;
  return d;
}

IndexerWeights FixtureWeights() {
  IndexerWeights w;
  w.wq_b = g::kWqB;
  w.wk = g::kWk;
  w.k_norm_weight = g::kKNormWeight;
  w.k_norm_bias = g::kKNormBias;
  w.weights_proj = g::kWeightsProj;
  w.kpool_ape = g::kKpoolApe;
  w.kpool_gate = g::kKpoolGate;
  return w;
}

std::vector<float> Hidden() { return Vec(g::kHiddenStates); }
std::vector<float> QResid() { return Vec(g::kQResid); }
std::vector<uint8_t> Mask() {
  return Bytes(g::kMask, static_cast<size_t>(g::kBatch * g::kSeqLen));
}

// The REAL published `config.json`, the same verbatim fixture the W1 scaffold
// gate reads. Its `index_kpool` is 4.
vllm::HfConfig PublishedConfig() {
  const std::string path = std::string(GLM5_NEXT_CKPT_FIXTURE_DIR) + "/config.json";
  std::ifstream in(path);
  REQUIRE_MESSAGE(in.good(), "missing fixture: " << path);
  return vllm::ParseHfConfig(nlohmann::json::parse(in), path);
}

// The set of REAL token indices a row selects. -1 is the invalid sentinel and
// duplicates are possible (upstream absorbs them with `scatter_add_` + `ne(0)`),
// so a set is the right comparison and a positionwise one would be stricter than
// the model's own semantics. The positionwise check is done separately below.
std::set<int32_t> SelectedSet(const int32_t* row, int64_t width) {
  std::set<int32_t> s;
  for (int64_t i = 0; i < width; ++i) {
    if (row[i] >= 0) s.insert(row[i]);
  }
  return s;
}

