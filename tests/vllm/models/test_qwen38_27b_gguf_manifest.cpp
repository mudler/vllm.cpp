// QUANT-QWEN38-27B-GGUF-ARM (issue #821, W2) — the tensor accounting this
// family has never had.
//
// Before this file NO Qwen3.5-family checkpoint-index accounting test existed
// anywhere under `tests/`: `test_gguf_qwen36_loader.cpp` builds synthetic files
// and asserts what the loader does with the tensors it ASKS FOR, and a fixture
// cannot disagree with its own author about which tensors a real checkpoint
// ships. So the direction that had no gate is the one that is silent — a tensor
// the file carries and no loader reads is dropped without a word.
//
// That direction is not hypothetical on this artifact. `Qwen3.8-27B-Q4_K_M.gguf`
// states `qwen35.block_count = 65` and `qwen35.nextn_predict_layers = 1`: 64
// decoder blocks plus an MTP drafter at `blk.64`. A reader that spends the whole
// 65 on the trunk builds a 65-layer model out of a 64-layer checkpoint plus a
// drafter, loads, decodes fluently, and is the wrong graph.
//
// The manifest (`qwen38_27b_q4km_gguf_manifest.inc`, generated by
// `scripts/gen-qwen38-27b-gguf-manifest.py`) freezes that file's 866 tensor
// names, ggml dims and type ids plus its scalar metadata — no weight bytes — so
// this runs in CI with no asset. The two live cases at the bottom re-derive the
// same numbers from the shipped bytes and SKIP LOUDLY when the env vars are
// unset, exactly as `test_clip_mmproj_gguf`'s live case does.
