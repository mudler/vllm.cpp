std::vector<std::string> Q4KMNames() {
  std::vector<std::string> out;
  for (const auto& t : vllm_test::kQwen38Q4KMTensors) out.emplace_back(t.name);
  return out;
}

std::vector<std::string> MmprojNames() {
  std::vector<std::string> out;
  for (const auto& t : vllm_test::kQwen38MmprojTensors) out.emplace_back(t.name);
  return out;
}

// A KV-ONLY GGUF carrying the manifest's `qwen35.*` scalars, so
// `HfConfigFromGguf` — the PRODUCTION config builder — is what derives the
// decoder depth here, rather than this test restating its arithmetic.
//
// ONE key is added that the file does not ship: `qwen35.vocab_size`. The real
// artifact states its vocabulary only through `token_embd.weight`'s shape, and
// that tensor is 1.27e9 Q4_K elements, which is not a thing a hermetic fixture
// can carry. The value comes from the MANIFEST's own record of that shape
// (`kQwen38Q4KMVocabSize`, the generator reading the file's dims), and the case
// below asserts the two agree, so the injection is bound to the bytes rather
// than hand-written. The env-gated live case exercises the shape fallback
// itself, on the real file, with nothing injected.
std::string BuildQ4KMMetadataOnlyGguf() {
  GgufModelBuilder b;
  for (const auto& kv : vllm_test::kQwen38Q4KMStringKv) {
    const std::string key(kv.key);
    if (key == "general.architecture") b.AddKv(gguf_test::StrKv(key, kv.value));
  }
  for (const auto& kv : vllm_test::kQwen38Q4KMIntKv) {
    const std::string key(kv.key);
    if (key.rfind("qwen35.", 0) != 0) continue;
    if (kv.value <= 0xffffffffLL) {
      b.AddKv(gguf_test::U32Kv(key, static_cast<uint32_t>(kv.value)));
    } else {
      b.AddKv(gguf_test::U64Kv(key, static_cast<uint64_t>(kv.value)));
    }
  }
  for (const auto& kv : vllm_test::kQwen38Q4KMFloatKv) {
    const std::string key(kv.key);
    if (key.rfind("qwen35.", 0) != 0) continue;
    b.AddKv(gguf_test::F32Kv(key, static_cast<float>(kv.value)));
  }
  b.AddKv(gguf_test::U32Kv(
      "qwen35.vocab_size",
      static_cast<uint32_t>(vllm_test::kQwen38Q4KMVocabSize)));
  return b.Build();
}

int64_t ManifestInt(const char* key) {
  for (const auto& kv : vllm_test::kQwen38Q4KMIntKv) {
    if (std::string(kv.key) == key) return kv.value;
  }
  return -1;
}

int64_t MmprojInt(const char* key) {
  for (const auto& kv : vllm_test::kQwen38MmprojIntKv) {
    if (std::string(kv.key) == key) return kv.value;
  }
  return -1;
}

std::string Join(const std::vector<std::string>& names) {
  std::string s;
  for (size_t i = 0; i < names.size() && i < 12; ++i) {
    s += (i == 0 ? "" : ", ") + names[i];
  }
  if (names.size() > 12) s += ", ...";
  return s;
}

