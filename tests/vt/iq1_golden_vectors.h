// Golden decode vectors for the two IQ1 encodings, produced by the ORACLES
// THEMSELVES rather than by this tree.
//
// Why this file exists. Every other check on the IQ1_S / IQ1_XXXS decode is
// self-consistent: `ReferenceDotF64` and the G3 NMSE reference both decode the
// weight with `vt::cpu::BlockToFloat`, which is the function under test, so
// they are independent only in the summation. The grid tables are sealed by
// digest, but a seal on the codebook says nothing about the SCALE field, the
// DELTA magnitude, or the DELTA SIGN. Three separate defects were injected into
// those three parameters and the whole suite stayed green. This fixture is the
// external reference that closes that hole.
//
// Provenance of the INPUTS. These are real bytes from the checkpoints the row
// targets, read out of the GGUF tensor data with a standalone header parser
// (`unsloth/Qwen3.8-2.4T-A95B-GGUF`, shard 2 of each split, tensor
// `blk.0.ffn_gate_exps.weight`, first four 256-element blocks):
//
//   IQ1_S    UD-IQ1_S  shard 00002-of-00012, ggml type 19, 4 x 50 = 200 bytes
//   IQ1_XXXS UD-Q1_0   shard 00002-of-00010, ggml type 66, 4 x 38 = 152 bytes
//
// Real bytes, not synthetic ones, because a synthetic block cannot catch a
// misreading of the FILE. The four blocks carry both delta-sign polarities and
// sub-block scales 2 through 7, so every field the decode reads varies inside
// the fixture. This also reproduces, as a committed slice, the 1179648-weight
// bit-identity run the spec records.
//
// Provenance of the EXPECTED VALUES. Each blob was decoded by the pinned
// oracle's own `ggml_get_type_traits(type)->to_float`, in a build of that
// oracle, and the f32 results are stored here as raw bit patterns:
//
//   IQ1_S    ggml-org/llama.cpp  @ 237ad9b96                (.agents/upstream-sync.md)
//   IQ1_XXXS unslothai/llama.cpp @ 36fe8e1cc7f2b3b8c92fdda0ab07600141921786
//                                                          (.agents/oracles/llama-cpp-unsloth.md)
//
// Reproduce with:
//   git -C <oracle> checkout <rev> && cmake -B build -DGGML_CUDA=OFF &&
//     cmake --build build --target ggml -j8
//   then call ggml_get_type_traits(19|66)->to_float on the bytes below.
//
// The comparison is BIT-EXACT, not approximate. `dl * (grid[j] + delta)` is
// the same f32 expression on both sides, so any difference at all means a
// decode parameter diverged rather than that rounding moved.
