// Golden `vec_dot` results for IQ2_XS (ggml type 17) and IQ4_XS (ggml type 23),
// produced by the ORACLE'S OWN KERNELS rather than by this tree. Companion to
// `iq2xs_iq4xs_golden_vectors.h`, which gates the DECODERS the same way: the
// weight bytes dotted here are that header's `kIq2xsGoldenBlocks` /
// `kIq4xsGoldenBlocks` arrays, re-verified byte-for-byte against the live
// artifact on 2026-08-29 (sha256 da5ab7fc… and 13cdb068… over the 296- and
// 544-byte slices read back by `dd` at the offsets that header records).
//
// A `vec_dot` is a REDUCTION, so a wrong grid entry, a swapped scale nibble or
// a mis-shifted `scales_h` bit pair does not throw and does not obviously
// misbehave — it moves the sum a little. The only check that separates "right"
// from "plausible" is the oracle's own number, and it is compared BIT for BIT
// against the oracle's OWN ACCUMULATION ORDER (upstream accumulates `sumf` in
// f32, one term per super-block, and this tree does the same). A cleaner f64
// reference would agree with a reduction-order defect and hide it, so no such
// reference is used here.
//
// Provenance of the WEIGHT bytes: real slices of the staged
// `unsloth/GLM-5.3-Flash-GGUF` UD-Q2_K_XL artifact under
// `/mnt/nas_share/rc/ckpt/GLM-5.3-Flash-UD-Q2_K_XL/`, shard 00002-of-00004 —
// `blk.3.ffn_gate_exps.weight` (IQ2_XS, 4 blocks) and
// `blk.11.ffn_down_exps.weight` (IQ4_XS, 4 blocks). See the companion header
// for the offsets and for what those particular blocks exercise.
//
// Provenance of the ACTIVATION bytes: the oracle's own
// `quantize_row_q8_K_generic` (ggml/src/ggml-cpu/quants.c:121) over a
// deterministic integer-valued f32 signal, so the activation side is the
// oracle's encoding rather than ours. `MakeDotActivation` in
// tests/vt/test_ops_quant_dot.cpp regenerates that signal EXACTLY — every value
// is an integer in [-1024, 1023] divided by 64, so it is representable to the
// bit in binary32 on any compiler — which lets the test also assert that OUR
// `from_float(Q8_K)` reproduces these bytes. Seeds 0x2247 (IQ2_XS) and 0x4247
// (IQ4_XS); the two differ so a defect cannot cancel across both cases.
//
// Reproduce (one command per line break):
//
//   git -C <fresh clone> archive 10bf611e533d81f739128304991c5e133c6aebd8 ggml
//       | tar -x -C $W
//   gcc -O2 -DGGML_VERSION='"b10451"' -DGGML_COMMIT='"10bf611e5"'
//       -I $W/ggml/include -I $W/ggml/src -I $W/ggml/src/ggml-cpu
//       -o harness harness.c stubs.c $W/ggml/src/ggml-cpu/quants.c
//       $W/ggml/src/ggml-quants.c $W/ggml/src/ggml.c -lm
//
// where `harness.c` calls `ggml_vec_dot_iq2_xs_q8_K_generic` (quants.c:948) and
// `ggml_vec_dot_iq4_xs_q8_K_generic` (quants.c:1283) on those bytes, and
// `stubs.c` supplies the five backend symbols `ggml.c` references and this
// dot-only harness never calls (they abort if reached, so a stub can never
// quietly contribute to a golden value) plus `ggml_table_f32_f16`, which
// ggml-cpu.c:80 owns and ggml-cpu.c:3840-3849 fills with
// `GGML_COMPUTE_FP16_TO_FP32` over every u16 — reproduced verbatim rather than
// dragging the whole CPU backend in.
//
// The harness also printed the oracle's own `sizeof(block_iq2_xs)` = 74,
// `sizeof(block_iq4_xs)` = 136 and `sizeof(block_q8_K)` = 292.
//
// The pairing IQ4_XS -> Q8_K is NOT assumed from IQ4_NL's shape: it is read off
// `type_traits_cpu` at ggml/src/ggml-cpu/ggml-cpu.c:385-390, whose row is
// `.vec_dot = ggml_vec_dot_iq4_xs_q8_K, .vec_dot_type = GGML_TYPE_Q8_K`.
// IQ4_NL (ggml-cpu.c:379-384) pairs with Q8_0 because its block is 32 elements;
// IQ4_XS shares IQ4_NL's 16-entry codebook but its block is a 256-element
// super-block, so it pairs with the 256-element activation encoding.
