// Golden decode vectors for IQ2_XS (ggml type 17) and IQ4_XS (ggml type 23),
// produced by the ORACLE ITSELF rather than by this tree. Same contract as
// `iq1_golden_vectors.h` and `iq4nl_q5_0_golden_vectors.h`, and it exists for
// the same reason: every other check on a new decoder in this tree routes
// through `vt::cpu::BlockToFloat`, which is the function under test, so it is
// independent only in the summation.
//
// Provenance of the INPUTS. REAL bytes from the staged checkpoint, not
// synthetic ones, because a synthetic block cannot catch a misreading of the
// FILE and a hand-written one does not exercise a 512-entry codebook. Both
// slices were read (read-only, by seek) from
// `/mnt/nas_share/rc/ckpt/GLM-5.3-Flash-UD-Q2_K_XL/`, the staged
// `unsloth/GLM-5.3-Flash-GGUF` UD-Q2_K_XL arm, shard
// `GLM-5.3-Flash-UD-Q2_K_XL-00002-of-00004.gguf`:
//
//   IQ2_XS  `blk.3.ffn_gate_exps.weight`  [4096, 2048, 288], absolute file
//           offset 2471843136 (data section starts at 42176; the tensor's
//           recorded offset is 2471800960), first 296 bytes = FOUR whole
//           74-byte blocks, a quarter of that tensor's 4096-wide row.
//           This is the exact tensor `LoadedEngine::FromModelDir` stopped on.
//   IQ4_XS  `blk.11.ffn_down_exps.weight` [2048, 4096, 288], absolute file
//           offset 21156866880 (recorded offset 21156824704), first 544 bytes
//           = FOUR whole 136-byte blocks, half of that tensor's 2048-wide row.
//
// The blocks are not uniform, which is the point: across the four IQ2_XS
// blocks the 32 `qs` u16 of each block carry 25-32 DISTINCT 9-bit grid indices
// and 25-30 DISTINCT 7-bit sign selectors, so both the codebook lookup and the
// `ksigns_iq2xs` sign path are exercised on live values rather than on zero.
// Across the four IQ4_XS blocks the 6-bit super-block scale `ls` takes values
// from 0 to 61, i.e. BOTH nibbles of `scales_l` and BOTH bit pairs of the
// 16-bit `scales_h` extension, and `dl = d * (ls - 32)` comes out positive for
// some sub-blocks and negative for others. An all-zero block would have proved
// none of that.
//
// Provenance of the EXPECTED VALUES. Both blobs were decoded by the pinned
// oracle's own `dequantize_row_iq2_xs` / `dequantize_row_iq4_xs`, compiled from
// ggml-org/llama.cpp @ `b10451` == 10bf611e533d81f739128304991c5e133c6aebd8
// (.agents/oracles/llama-cpp.md), and the f32 results are stored here as raw
// bit patterns.
//
// The source tree was NOT the developer's working checkout, which carries local
// modifications: it was extracted with `git archive <sha> ggml`, so the bytes
// compiled are the pinned commit's own. Reproduce with:
//
//   git -C <llama.cpp> archive 10bf611e533d81f739128304991c5e133c6aebd8 ggml
//       | tar -x -C $W
//   gcc -O2 -DGGML_VERSION='"b10451"' -DGGML_COMMIT='"10bf611e5"'
//       -I $W/ggml/include -I $W/ggml/src -I $W/ggml/src/ggml-cpu
//       -o harness harness.c stubs.c $W/ggml/src/ggml-quants.c
//       $W/ggml/src/ggml.c -lm
//
// (one command; the line breaks above are for width only)
//
// where `harness.c` calls the two `dequantize_row_*` entry points on the bytes
// below and `stubs.c` supplies the five backend symbols `ggml.c` references and
// this dequant-only harness never calls (they abort if reached, so a stub can
// never quietly contribute to a golden value). The harness also printed the
// oracle's own `sizeof(block_iq2_xs)` = 74 and `sizeof(block_iq4_xs)` = 136,
// which is where the two block strides registered in `vt::dtype` and in the
// reader's `GgmlTraits` come from.
//
// The comparison is BIT-EXACT, not approximate. Both decoders are the same f32
// expression on both sides, so any difference at all means a decode parameter
// diverged rather than that rounding moved.
