// Golden decode vectors for IQ3_S (ggml type 21), produced by the ORACLE ITSELF
// rather than by this tree. Same contract as `iq2xs_iq4xs_golden_vectors.h` and
// `iq4nl_q5_0_golden_vectors.h`, and it exists for the same reason: every other
// check on a new decoder in this tree routes through `vt::cpu::BlockToFloat`,
// which is the function under test, so it is independent only in the summation.
//
// Provenance of the INPUTS. REAL bytes from the staged checkpoint, not synthetic
// ones, because a synthetic block cannot catch a misreading of the FILE and a
// hand-written one does not exercise a 512-entry codebook. The slice was read
// (read-only, by seek) from
// `/mnt/nas_share/rc/ckpt/qwen38-27b-ud-q4km/Qwen3.8-27B-UD-Q4_K_M.gguf`
// (16,464,440,224 B, sha256
// 322e194ff79741c7baa497c240f677f54b201b0efab44ca8e50f122b39123482), the staged
// `unsloth/Qwen3.8-27B-GGUF` UD-Q4_K_M arm:
//
//   IQ3_S  `blk.11.ffn_gate.weight`  [5120, 17408], absolute file offset
//          4262628128 (the data section starts at 10996640; the tensor's
//          recorded offset is 4251631488), first 440 bytes = FOUR whole
//          110-byte blocks out of that tensor's 348,160.
//
// That is one of exactly FOUR IQ3_S tensors in an 866-tensor file, and it is the
// tensor `GgufFile::Open` refused with `unknown ggml type id 21` (#2510).
//
// The blocks are not uniform, which is the point. Across the four blocks the
// reconstructed 9-bit grid indices take 190 DISTINCT values of which 73 are
// >= 256 -- so the ninth bit, the one spliced out of `qh` with the asymmetric
// `<< (8-2*l)` / `<< (7-2*l)` shift pair, is genuinely exercised rather than
// left at zero. The 32 direct sign bytes take 104 distinct values across the
// four blocks, the 4-bit sub-block scales span 6..15, and all 1024 decoded
// values are non-zero with 508 of them negative. An all-zero block would have
// proved none of that.
//
// Provenance of the EXPECTED VALUES. The blob was decoded by the pinned oracle's
// own `dequantize_row_iq3_s`, compiled from ggml-org/llama.cpp @ `b10451` ==
// 10bf611e533d81f739128304991c5e133c6aebd8 (.agents/oracles/llama-cpp.md), and
// the f32 results are stored here as raw bit patterns.
//
// The source tree was NOT the developer's working checkout, which carries local
// modifications: it was extracted with `git archive <sha> ggml`, so the bytes
// compiled are the pinned commit's own. Reproduce with:
//
//   git -C <llama.cpp> archive 10bf611e533d81f739128304991c5e133c6aebd8 ggml
//       | tar -x -C $W
//   gcc -O2 -DGGML_VERSION='"b10451"' -DGGML_COMMIT='"10bf611e5"'
//       -I $W/ggml/include -I $W/ggml/src -I $W/ggml/src/ggml-cpu
//       -o harness harness.c stubs.c $W/ggml/src/ggml-quants.c
//       $W/ggml/src/ggml.c -lm
//
// (one command; the line breaks above are for width only)
//
// where `harness.c` calls `dequantize_row_iq3_s` on the bytes below and
// `stubs.c` supplies the five backend symbols `ggml.c` references and this
// dequant-only harness never calls (they abort if reached, so a stub can never
// quietly contribute to a golden value). The harness also printed the oracle's
// own `sizeof(block_iq3_s)` = 110, which is where the block stride registered in
// `vt::dtype` and in the reader's `GgmlTraits` comes from -- it is measured, not
// read off the struct.
//
// The comparison is BIT-EXACT, not approximate. Both decoders are the same f32
// expression on both sides, so any difference at all means a decode parameter
// diverged rather than that rounding moved.
