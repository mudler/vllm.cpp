// Golden decode vectors for IQ4_NL (ggml type 20) and Q5_0 (ggml type 6),
// produced by the ORACLE ITSELF rather than by this tree. Same contract as
// `iq1_golden_vectors.h`, and it exists for the same reason: every other check
// on a new decoder in this tree routes through `vt::cpu::BlockToFloat`, which
// is the function under test, so it is independent only in the summation.
//
// Provenance of the IQ4_NL INPUTS. REAL bytes, not synthetic ones, because a
// synthetic block cannot catch a misreading of the FILE. They are the first
// 180 bytes of `per_layer_token_embd.weight` in
// `unsloth/Qwen3.8-Flash-Next-GGUF` @ revision 8bdc666649440e9bdc97e16f3f75782c98478ff5,
// path `UD-IQ1_S/Qwen3.8-Flash-Next-UD-IQ1_S-00002-of-00003.gguf`, read live
// 2026-08-26 with an HTTP range request rather than by downloading the 25 GB
// shard. The revision is pinned because that repo was still being uploaded when
// these bytes were read. That tensor is IQ4_NL `[160, 320001536]`, so 180 bytes is exactly TEN
// 32-element blocks == TWO WHOLE GATHER ROWS of the n-gram table this row
// exists to make loadable. The absolute file offset was computed from the
// shard's own header: data section starts at 37696 (header ends 37683, aligned
// up to `general.alignment` = 32) and the tensor's recorded offset is
// 364584960, so the bytes begin at 364622656.
//
// Provenance of the Q5_0 INPUTS. SYNTHETIC, and deliberately so: NO tensor in
// any published Qwen3.8-Flash-Next GGUF is Q5_0. It is carried because
// llama.cpp's `tensor_type_fallback` maps `Q4_K -> Q5_0` for a row that is not
// a multiple of 256, which every `qwen4exp` expert row (640) and table row
// (160) is, so a `-Q4_K_M` build of this model lands on it. The bytes come
// from a fixed LCG (seed 0x9E3779B9, `x = x*1664525 + 1013904223`, high byte)
// with an f16-exact delta per block, which is reproducible anywhere and covers
// both halves of the `qh` bit plane — the field a naive port gets wrong,
// because the two halves read it through DIFFERENT shift expressions.
//
// Provenance of the EXPECTED VALUES. Both blobs were decoded by the pinned
// oracle's own `dequantize_row_iq4_nl` / `dequantize_row_q5_0`, compiled from
// ggml-org/llama.cpp @ `b10451` == 10bf611e533d81f739128304991c5e133c6aebd8
// (.agents/oracles/llama-cpp.md), and the f32 results are stored here as raw
// bit patterns.
//
// The source tree was NOT the developer's working checkout, which carries
// local modifications: it was extracted with `git archive b10451 ggml`, so the
// bytes compiled are the tag's own. Reproduce with:
//
//   git -C <llama.cpp> archive b10451 ggml | tar -x -C $W
//   gcc -O2 -DGGML_VERSION='"b10451"' -DGGML_COMMIT='"10bf611e5"'
//       -I $W/ggml/include -I $W/ggml/src -I $W/ggml/src/ggml-cpu
//       -o harness harness.c stubs.c $W/ggml/src/ggml-quants.c
//       $W/ggml/src/ggml.c -lm
//
// (one command; the line breaks above are for width only)
//
// where `harness.c` calls the two `dequantize_row_*` entry points on the bytes
// below and `stubs.c` supplies the five backend symbols `ggml.c` references and
// this dequant-only harness never calls (they abort if reached).
//
// The comparison is BIT-EXACT, not approximate. Both decoders are the same f32
// expression on both sides, so any difference at all means a decode parameter
// diverged rather than that rounding moved.
